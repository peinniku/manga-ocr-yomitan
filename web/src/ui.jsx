export function Icon({ name, size = 20, class: cls = '' }) {
  return (
    <svg
      class={`icon ${cls}`}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      stroke-width="2"
      stroke-linecap="round"
      stroke-linejoin="round"
      aria-hidden="true"
    >
      {ICONS[name]}
    </svg>
  );
}

/** Speaker button; doesn't trigger whatever it sits on (e.g. flipping the card). */
export function Say({ req, title }) {
  return (
    <button
      class="say"
      type="button"
      title={title}
      aria-label={title}
      onClick={(ev) => {
        ev.stopPropagation();
        play(req);
      }}
    >
      <Icon name="speaker" size={18} />
    </button>
  );
}

/** Centered message for empty states (as on the desktop). */
export function Empty({ title, hint }) {
  return (
    <div class="empty">
      <h2>{title}</h2>
      {hint && <p>{hint}</p>}
    </div>
  );
}

/** Bordered settings section: title, muted description, then content. */
export function Section({ title, desc, children }) {
  return (
    <section class="section">
      <div class="section-head">
        <h3>{title}</h3>
        {desc && <p>{desc}</p>}
      </div>
      {children}
    </section>
  );
}
